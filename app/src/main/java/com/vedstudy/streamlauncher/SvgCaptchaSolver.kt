    private data class PathItem(val x: Double, val pathD: String)

    fun solve(svgXml: String): String {
        val paths = mutableListOf<PathItem>()

        val pattern = Pattern.compile("<path\\s+[^>]*d=\"([^\"]+)\"[^>]*transform=\"([^\"]+)\"")
        var matcher = pattern.matcher(svgXml)

        while (matcher.find()) {
            val d = matcher.group(1) ?: continue
            val transform = matcher.group(2) ?: ""
            val x = extractTranslateX(transform)
            paths.add(PathItem(x, d))
        }

        if (paths.isEmpty()) {
            val altPattern = Pattern.compile("<path\\s+[^>]*transform=\"([^\"]+)\"[^>]*d=\"([^\"]+)\"")
            matcher = altPattern.matcher(svgXml)
            while (matcher.find()) {
                val transform = matcher.group(1) ?: ""
                val d = matcher.group(2) ?: continue
                val x = extractTranslateX(transform)
                paths.add(PathItem(x, d))
            }
        }

        // Sort by X coordinate from left to right
        paths.sortBy { it.x }

        val solution = StringBuilder()
        for (item in paths) {
            val matched = KNOWN_DIGITS[item.pathD]
            if (matched != null) {
                solution.append(matched)
            } else {
                // Heuristic fallback matching by path characteristics
                val fallback = classifyByPrefix(item.pathD)
                solution.append(fallback)
            }
        }

        return solution.toString()
    }

    private fun extractTranslateX(transform: String): Double {
        val tm = Pattern.compile("translate\\(\\s*([\\d\\.\\-]+)[\\s,]+([\\d\\.\\-]+)\\s*\\)").matcher(transform)
        return if (tm.find()) {
            tm.group(1)?.toDoubleOrNull() ?: 0.0
        } else 0.0
    }

